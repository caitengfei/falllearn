def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--commit", action="store_true")
    args = ap.parse_args()

    conn = sqlite3.connect(args.db)
    conn.row_factory = sqlite3.Row
    exist = {norm(r["stem"]) for r in conn.execute("SELECT stem FROM questions")}
    maxid = conn.execute("SELECT COALESCE(MAX(id),0) FROM questions").fetchone()[0]

    new, dup = [], 0
    for cl, qtype, diff, stem, opts, ans, src in Q:
        if norm(stem) in exist:
            dup += 1
            continue
        exist.add(norm(stem))
        new.append(dict(cluster_id=cl, qtype=qtype, difficulty=diff, stem=stem, options=opts,
                        answer=ans, source_doc=src))
    from collections import Counter
    print(f"待入库 {len(new)} 题（重复跳过 {dup}）")
    print("分簇：", dict(Counter(r["cluster_id"] for r in new)))
    print("题型：", dict(Counter(r["qtype"] for r in new)))
    if not args.commit:
        print("（dry-run；加 --commit 写入）")
        return
    nid = maxid
    for r in new:
        nid += 1
        conn.execute("INSERT INTO questions(id,qtype,cluster_id,difficulty,stem,options,answer,source_doc,origin)"
                     " VALUES(?,?,?,?,?,?,?,?,?)",
                     (nid, r["qtype"], r["cluster_id"], r["difficulty"], r["stem"],
                      json.dumps(r["options"], ensure_ascii=False), r["answer"], r["source_doc"], ORIGIN))
    conn.commit()
    print(f"✔ 写入 {len(new)} 题；总题数 {conn.execute('SELECT COUNT(*) FROM questions').fetchone()[0]}")
    print("--- 分簇 ---")
    for r in conn.execute("SELECT cluster_id, COUNT(*) n FROM questions GROUP BY cluster_id ORDER BY n DESC"):
        print(f"  {str(r['cluster_id']):<10} {r['n']}")
    if os.path.abspath(args.db) == os.path.abspath(DEFAULT_DB):
        seed = json.load(open(SEED, encoding="utf-8"))
        n0 = len(seed)
        for r in new:
            seed.append({"origin": ORIGIN, "type": r["qtype"], "stem": r["stem"], "options": r["options"],
                         "answer": r["answer"], "source_doc": r["source_doc"],
                         "cluster": CLUSTER_CN[r["cluster_id"]], "difficulty": r["difficulty"]})
        json.dump(seed, open(SEED, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"seed：{n0} → {len(seed)}")


if __name__ == "__main__":
    main()
